/** Códigos de monto (haberes / descuentos / aportes) vs identificación / totales. */
export function esCodigoMontoLre(codigo: string): boolean {
  const n = Number(codigo);
  return Number.isFinite(n) && n >= 2101 && n < 5200;
}

export function esCodigoTotalLre(codigo: string): boolean {
  const n = Number(codigo);
  return Number.isFinite(n) && n >= 5201 && n <= 5565;
}
